/** Maps a validation / action error code to a Greek message. */
export function errorMessage(code: string | undefined): string | undefined {
  if (!code) return undefined;
  const pools: Array<Record<string, unknown>> = [t.excursions, t.announcements, t.settings];
  for (const pool of pools) {
    const v = pool[code];
    if (typeof v === "string") return v;
  }
  if (code === "tooLong") return "Το κείμενο είναι πολύ μεγάλο.";
  return t.common.error;
}

export function fmt(s: string, vars: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ""));
}
